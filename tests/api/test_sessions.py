class TestRevocationReasons:
    @requires_db
    def test_an_unknown_reason_is_refused(self) -> None:
        """Free text cannot be aggregated. "How many sessions did an administrator
        end last week" is unanswerable over a column of prose."""

        async def scenario(cur: psycopg.AsyncCursor[tuple[object, ...]]) -> None:
            org_id, user_id = await _org_and_user(cur)
            session_id = await record_session(
                cur,
                organization_id=org_id,
                user_id=user_id,
                token=unique("tok"),
                expires_at=_later(),
            )
            await revoke_session(
                cur,
                organization_id=org_id,
                session_id=session_id,
                reason="because I felt like it",
                actor_id=None,
            )

        with pytest.raises(SessionError, match="unknown revocation reason"):
            run_as_owner(scenario)

    @requires_db
    def test_the_database_refuses_a_revocation_without_a_reason(self) -> None:
        """Enforced by CHECK, not by remembering. A revoked_at with no reason means
        one of the two writes was forgotten."""

        async def scenario(cur: psycopg.AsyncCursor[tuple[object, ...]]) -> None:
            org_id, user_id = await _org_and_user(cur)
            session_id = await record_session(
                cur,
                organization_id=org_id,
                user_id=user_id,
                token=unique("tok"),
                expires_at=_later(),
            )
            await cur.execute(
                "UPDATE sessions SET revoked_at = now() WHERE id = %s", (str(session_id),)
            )

        with pytest.raises(psycopg.errors.CheckViolation):
            run_as_owner(scenario)


# --- expiry still works -------------------------------------------------------


class TestExpiry:
    @requires_db
    def test_an_expired_session_is_refused(self) -> None:
        """Revocation must not have replaced expiry."""
        token = unique("tok")

        async def scenario(cur: psycopg.AsyncCursor[tuple[object, ...]]) -> str:
            org_id, user_id = await _org_and_user(cur)
            await record_session(
                cur, organization_id=org_id, user_id=user_id, token=token, expires_at=_later(1)
            )
            outcome = await validate_session(
                cur, token=token, now=datetime.now(UTC) + timedelta(hours=2)
            )
            return str(outcome.reason)

        assert run_as_owner(scenario) == "expired"

    @requires_db
    def test_recording_an_already_expired_session_is_refused(self) -> None:
        async def scenario(cur: psycopg.AsyncCursor[tuple[object, ...]]) -> None:
            org_id, user_id = await _org_and_user(cur)
            await record_session(
                cur,
                organization_id=org_id,
                user_id=user_id,
                token=unique("tok"),
                expires_at=datetime.now(UTC) - timedelta(minutes=1),
            )

        with pytest.raises(SessionError, match="already expired"):
            run_as_owner(scenario)

    def test_a_naive_expiry_is_refused(self) -> None:
        """DTZ: a naive datetime compared against an aware one raises at runtime,
        and the place to find that out is not production."""

        async def scenario(cur: psycopg.AsyncCursor[tuple[object, ...]]) -> None:
            await record_session(
                cur,
                organization_id=uuid.uuid4(),
                user_id=uuid.uuid4(),
                token="t",  # noqa: S106 - a session token, not a password
                expires_at=datetime(2030, 1, 1),  # noqa: DTZ001 - the point of the test
            )

        class _Dead:
            async def execute(self, q: str, p: tuple[object, ...] = (), /) -> object:
                raise AssertionError("must refuse before touching the database")

            async def fetchone(self) -> tuple[object, ...] | None:
                return None

            async def fetchall(self) -> list[tuple[object, ...]]:
                return []

        with pytest.raises(SessionError, match="timezone-aware"):
            asyncio.run(scenario(_Dead()))  # type: ignore[arg-type]
