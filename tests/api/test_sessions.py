"""Session store and revocation — TST-SEC-003 · STEP-002.08.

WHAT THESE ARE PROVING
    That a credential already in someone's hands stops working. Every other test
    in this file exists to stop that one from becoming vacuous — a store whose
    revocation only takes effect at expiry passes a naive "revoke then check the
    flag" test while changing nothing about what an attacker can do.

    So the central assertion is always: revoke, then present the token, **before
    its natural expiry**, and require refusal.
"""

